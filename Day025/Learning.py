# OOP in Python
# To map with real world scenarios, we started using objects in code.
# This is called object oriented programming.
# Class & Object in Python
# Class is a biueprint for creating objects.
class Student:
    name = "Karan"
# creating objects (instance)
s1 = Student()
print(s1.name)

class Car:
    color = "blue"
    model = "G 65"
car1 = Car()
print(car1.color)
print(car1.model)